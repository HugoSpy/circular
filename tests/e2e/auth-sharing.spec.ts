import { test, expect } from './fixtures';
import type { Page } from '@playwright/test';
import { CircularPage } from './pages/circular-page';
import { createEmptyWorkspace } from './workspace-setup';

const password = 'Passphrase-test-2026!';
async function register(page: Page, username: string) {
  await page.getByRole('button', { name: 'Créer un compte', exact: true }).click();
  await page.getByRole('textbox', { name: 'Pseudo', exact: true }).fill(username);
  await page.getByRole('textbox', { name: 'Adresse e-mail EPITA', exact: true }).fill(`${username}@epita.fr`);
  await page.getByLabel('Mot de passe', { exact: true }).fill(password);
  await page.getByLabel('Confirmer le mot de passe', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Créer mon compte', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Créer votre espace', exact: true })).toBeVisible();
  await createEmptyWorkspace(page, new URL(page.url()).origin, username);
  await page.reload();
  await expect(page.getByRole('button', { name: 'Mon compte', exact: true })).toBeVisible();
}
async function login(page: Page, identifier: string, secret = password) {
  await page.getByRole('textbox', { name: 'Pseudo ou adresse e-mail', exact: true }).fill(identifier);
  await page.getByLabel('Mot de passe', { exact: true }).fill(secret);
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Mon compte', exact: true })).toBeVisible();
}
async function logout(page: Page) {
  await page.getByRole('button', { name: 'Mon compte', exact: true }).click();
  await page.getByRole('button', { name: 'Se déconnecter', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Se connecter', exact: true })).toBeVisible();
}
async function members(page: Page, project: string) {
  await page.getByRole('navigation', { name: 'Navigation principale' }).getByRole('button', { name: 'Projets', exact: true }).click();
  await page.getByRole('button', { name: `Membres de ${project}`, exact: true }).click();
  return page.getByRole('dialog', { name: `Membres de ${project}`, exact: true });
}

test('inscription EPITA, connexion pseudo, changement de mot de passe et déconnexion', async ({ page, server }, testInfo) => {
  await page.goto(server.url);
  await expect(page.getByRole('heading', { name: 'Se connecter', exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('login-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: 'Créer un compte', exact: true }).click();
  await page.getByRole('textbox', { name: 'Pseudo', exact: true }).fill('alice');
  const email = page.getByRole('textbox', { name: 'Adresse e-mail EPITA', exact: true });
  await email.fill('alice@example.org');
  await page.getByLabel('Mot de passe', { exact: true }).fill(password);
  await page.getByLabel('Confirmer le mot de passe', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Créer mon compte', exact: true }).click();
  expect(await email.evaluate(element => (element as HTMLInputElement).validity.valid)).toBe(false);
  await email.fill('alice@epita.fr');
  await page.getByRole('button', { name: 'Créer mon compte', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Créer votre espace', exact: true })).toBeVisible();
  await createEmptyWorkspace(page, server.url, 'alice');
  await page.reload();
  await expect(page.getByRole('button', { name: 'Mon compte', exact: true })).toBeVisible();
  const app = new CircularPage(page);
  await app.createProject('Projet personnel', 'PRIV');
  await app.createTicket({ title: 'Mon premier ticket privé' });
  await server.restart();
  await page.reload();
  await expect(app.row('Mon premier ticket privé')).toBeVisible();
  await logout(page);
  await login(page, 'alice');
  await expect(app.row('Mon premier ticket privé')).toBeVisible();
  await page.getByRole('button', { name: 'Mon compte', exact: true }).click();
  await page.getByLabel('Mot de passe actuel', { exact: true }).fill('Mauvais-mot-de-passe');
  await page.getByLabel('Nouveau mot de passe', { exact: true }).fill('Nouvelle-phrase-test-2026!');
  await page.getByLabel('Confirmer le nouveau mot de passe', { exact: true }).fill('Nouvelle-phrase-test-2026!');
  await page.getByRole('button', { name: 'Changer le mot de passe', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Mon compte', exact: true }).getByRole('alert')).toContainText('Mot de passe actuel incorrect');
  await page.getByLabel('Mot de passe actuel', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Changer le mot de passe', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Se connecter', exact: true })).toBeVisible();
  await page.getByRole('textbox', { name: 'Pseudo ou adresse e-mail', exact: true }).fill('alice');
  await page.getByLabel('Mot de passe', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click();
  await expect(page.getByRole('alert')).toBeVisible();
  await login(page, 'alice@epita.fr', 'Nouvelle-phrase-test-2026!');
  await expect(app.row('Mon premier ticket privé')).toBeVisible();
});

test('invitations annulées et refusées ne donnent aucun accès au projet', async ({ page, server }) => {
  await page.goto(server.url);
  await register(page, 'invite');
  await logout(page);
  await register(page, 'responsable');
  const app = new CircularPage(page);
  await app.createProject('Accès contrôlé', 'CTRL');
  let sharing = await members(page, 'Accès contrôlé');
  await sharing.getByRole('textbox', { name: 'Inviter par adresse e-mail', exact: true }).fill('invite@epita.fr');
  await sharing.getByRole('button', { name: 'Inviter', exact: true }).click();
  const cancel = sharing.getByRole('button', { name: 'Annuler l’invitation de invite@epita.fr', exact: true });
  await cancel.click();
  await expect(cancel).toHaveCount(0);
  await sharing.getByRole('button', { name: 'Fermer', exact: true }).click();
  await logout(page);
  await login(page, 'invite');
  await page.getByRole('button', { name: 'Invitations', exact: true }).click();
  let inbox = page.getByRole('dialog', { name: 'Invitations', exact: true });
  await inbox.getByRole('button', { name: 'Actualiser les invitations', exact: true }).click();
  await expect(inbox.getByText('Aucune invitation en attente.', { exact: true })).toBeVisible();
  await inbox.getByRole('button', { name: 'Fermer', exact: true }).click();
  await logout(page);
  await login(page, 'responsable');
  sharing = await members(page, 'Accès contrôlé');
  await sharing.getByRole('textbox', { name: 'Inviter par adresse e-mail', exact: true }).fill('invite@epita.fr');
  await sharing.getByRole('button', { name: 'Inviter', exact: true }).click();
  await expect(sharing.getByText('Invitation envoyée dans Circular. Aucun e-mail n’est envoyé.', { exact: true })).toBeVisible();
  await sharing.getByRole('button', { name: 'Fermer', exact: true }).click();
  await logout(page);
  await login(page, 'invite');
  await page.getByRole('button', { name: 'Invitations', exact: true }).click();
  inbox = page.getByRole('dialog', { name: 'Invitations', exact: true });
  await inbox.getByRole('button', { name: 'Refuser Accès contrôlé', exact: true }).click();
  await expect(inbox.getByText('Invitation refusée.', { exact: true })).toBeVisible();
  await inbox.getByRole('button', { name: 'Fermer', exact: true }).click();
  await page.getByRole('navigation', { name: 'Navigation principale' }).getByRole('button', { name: 'Projets', exact: true }).click();
  await expect(page.getByTestId(/^project-card-/)).toHaveCount(0);
  await server.restart();
  await page.reload();
  await page.getByRole('button', { name: 'Invitations', exact: true }).click();
  await expect(page.getByRole('dialog').getByText('Aucune invitation en attente.', { exact: true })).toBeVisible();
});

test('projet privé puis invitation acceptée, collaboration et révocation réelle', async ({ page, server }, testInfo) => {
  test.setTimeout(75_000);
  await page.goto(server.url);
  await register(page, 'proprietaire');
  const app = new CircularPage(page);
  await app.createProject('Projet partagé', 'PART');
  await app.createTicket({ title: 'Ticket réservé au projet' });
  await app.openTicket('Ticket réservé au projet');
  const privateUrl = page.url();
  await app.comment('Commentaire du propriétaire');
  await expect(app.detail.getByText('Commentaire du propriétaire', { exact: true })).toBeVisible();
  await app.closeDetail();
  await logout(page);
  await register(page, 'membre');
  await expect(app.rows).toHaveCount(0);
  await page.goto(privateUrl);
  await expect(page.getByRole('heading', { name: 'Espace inaccessible', exact: true })).toBeVisible();
  await expect(app.rows).toHaveCount(0);
  await page.getByRole('button', { name: 'Ouvrir Espace membre', exact: true }).click();
  await logout(page);
  await login(page, 'proprietaire');
  const sharing = await members(page, 'Projet partagé');
  await sharing.getByRole('textbox', { name: 'Inviter par adresse e-mail', exact: true }).fill('membre@epita.fr');
  await sharing.getByRole('button', { name: 'Inviter', exact: true }).click();
  await expect(sharing.getByText('Invitation envoyée dans Circular. Aucun e-mail n’est envoyé.', { exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('sharing-desktop.png'), fullPage: true });
  await sharing.getByRole('button', { name: 'Fermer', exact: true }).click();
  await logout(page);
  await login(page, 'membre');
  await expect(app.rows).toHaveCount(0);
  await page.getByRole('button', { name: 'Invitations', exact: true }).click();
  const inbox = page.getByRole('dialog', { name: 'Invitations', exact: true });
  await inbox.getByRole('button', { name: 'Accepter Projet partagé', exact: true }).click();
  await expect(inbox.getByText(/Vous avez rejoint/)).toBeVisible();
  await inbox.getByRole('button', { name: 'Fermer', exact: true }).click();
  await expect(app.row('Ticket réservé au projet')).toBeVisible();
  await page.getByRole('navigation', { name: 'Navigation principale' }).getByRole('button', { name: 'Projets', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Modifier Projet partagé', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Ouvrir le projet Projet partagé', exact: true }).click();
  await app.openTicket('Ticket réservé au projet');
  await expect(app.detail.getByText('proprietaire', { exact: true }).first()).toBeVisible();
  await expect(app.detail.getByRole('button', { name: 'Modifier le commentaire', exact: true })).toHaveCount(0);
  await app.comment('Réponse du membre');
  await expect(app.detail.getByText('Réponse du membre', { exact: true })).toBeVisible();
  await expect(app.detail.getByRole('button', { name: 'Modifier le commentaire', exact: true })).toHaveCount(1);
  await app.closeDetail();
  await logout(page);
  await login(page, 'proprietaire');
  const ownerDialog = await members(page, 'Projet partagé');
  page.once('dialog', dialog => dialog.accept());
  await ownerDialog.getByRole('button', { name: 'Retirer membre', exact: true }).click();
  await expect(ownerDialog.getByText('Accès au projet retiré.', { exact: true })).toBeVisible();
  await ownerDialog.getByRole('button', { name: 'Fermer', exact: true }).click();
  await logout(page);
  await login(page, 'membre');
  await expect(app.rows).toHaveCount(0);
  await page.goto(privateUrl);
  await expect(page.getByRole('dialog').getByRole('alert')).toBeVisible();
});

