test('une sauvegarde en attente du compte A ne modifie pas les préférences du compte B', async ({ page, server }) => {
  test.setTimeout(75_000);
  const workspaces = new WorkspacePage(page);
  const app = new CircularPage(page);
  await page.goto(server.url);
  await workspaces.register('queue-membre');
  await createEmptyWorkspace(page, server.url, 'queue-membre');
  await page.reload();
  await workspaces.logout();
  await workspaces.register('queue-owner');
  const owner = await createEmptyWorkspace(page, server.url, 'queue-owner');
  await page.reload();
  await app.createProject('Collaboration', 'COL');
  await app.createTicket({ title: 'Ticket partagé' });
  const invitation = await page.request.post(`${server.url}/api/workspaces/${owner.workspace.id}/invitations`, {
    headers: owner.headers, data: { email: 'queue-membre@epita.fr' },
  });
  expect(invitation.status()).toBe(201);
  const invitationId = (await invitation.json()).id;
  await workspaces.logout();
  await workspaces.login('queue-membre');
  const memberSession = await (await page.request.get(`${server.url}/api/auth/me`)).json();
  const accepted = await page.request.post(`${server.url}/api/workspace-invitations/${invitationId}/accept`, {
    headers: { 'X-CSRF-Token': memberSession.csrfToken }, data: {},
  });
  expect(accepted.ok()).toBeTruthy();
  await page.goto(`${server.url}/?workspace=queue-owner`);
  await expect(workspaces.menuButton).toContainText('Espace queue-owner');
  await app.search.fill('Recherche personnelle du membre');
  const scope = { 'X-Workspace-Id': String(owner.workspace.id) };
  await expect.poll(async () => (await (await page.request.get(`${server.url}/api/settings`, { headers: scope })).json()).filters.q).toBe('Recherche personnelle du membre');
  await workspaces.logout();
  await workspaces.login('queue-owner');
  await expect(app.search).toHaveValue('');

  let releaseFirst!: () => void;
  let firstSaved!: () => void;
  const release = new Promise<void>(resolve => { releaseFirst = resolve; });
  const saved = new Promise<void>(resolve => { firstSaved = resolve; });
  const requestedSearches: string[] = [];
  await page.route('**/api/settings', async route => {
    if (route.request().method() !== 'PATCH') return route.continue();
    const query = route.request().postDataJSON()?.filters?.q;
    if (typeof query === 'string') requestedSearches.push(query);
    if (query === 'Auteur : premier envoi') {
      // Commit A's first request, then hold its response so A's next edit queues.
      const response = await route.fetch();
      firstSaved();
      await release;
      await route.fulfill({ response });
    } else await route.continue();
  });
  try {
    await app.search.fill('Auteur : premier envoi');
    await saved;
    await app.search.fill('Auteur : modification en attente');
    await expect(app.search).toHaveValue('Auteur : modification en attente');
    // Account logout remains available while the preferences queue is pending.
    await page.getByRole('button', { name: 'Mon compte', exact: true }).click();
    await page.getByRole('dialog', { name: 'Mon compte', exact: true }).getByRole('button', { name: 'Se déconnecter', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Se connecter', exact: true })).toBeVisible();
    await workspaces.login('queue-membre');
    await workspaces.switchTo('Espace queue-owner');
    await expect(app.search).toHaveValue('Recherche personnelle du membre');
    const oldResponse = page.waitForResponse(response => response.url().endsWith('/api/settings') && response.request().method() === 'PATCH' && response.request().postDataJSON()?.filters?.q === 'Auteur : premier envoi');
    releaseFirst();
    expect((await oldResponse).status()).toBe(200);
    // Cross rendering turns after the old response is delivered; no sleep or
    // mocked storage is used to make the old promise queue settle.
    await page.evaluate(async () => {
      await new Promise<void>(resolve => requestAnimationFrame(() => resolve()));
      await new Promise<void>(resolve => requestAnimationFrame(() => resolve()));
    });
    await expect(app.search).toHaveValue('Recherche personnelle du membre');
    expect((await (await page.request.get(`${server.url}/api/settings`, { headers: scope })).json()).filters.q).toBe('Recherche personnelle du membre');
    await app.search.fill('Nouvelle recherche du membre');
    await expect.poll(async () => (await (await page.request.get(`${server.url}/api/settings`, { headers: scope })).json()).filters.q).toBe('Nouvelle recherche du membre');
    expect(requestedSearches).toContain('Auteur : premier envoi');
    expect(requestedSearches).toContain('Nouvelle recherche du membre');
    expect(requestedSearches).not.toContain('Auteur : modification en attente');
  } finally {
    releaseFirst();
    if (!page.isClosed()) await page.unroute('**/api/settings');
  }
  await server.restart();
  await page.reload();
  await expect(app.search).toHaveValue('Nouvelle recherche du membre');
});
