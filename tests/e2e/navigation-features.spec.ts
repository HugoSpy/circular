import { test, expect } from './fixtures';

test('vues nommées : enregistrer, modifier, restaurer et supprimer après redémarrage', async ({ app, page, server }) => {
  await app.createProject('Vues locales', 'VUE');
  await app.createTicket({ title: 'Alpha urgent', status: 'todo', priority: 'high' });
  await app.createTicket({ title: 'Bravo urgent', status: 'todo', priority: 'high' });
  await app.createTicket({ title: 'Charlie terminé', status: 'done', priority: 'low' });
  await app.statusFilter.selectOption('todo');
  await app.priorityFilter.selectOption('high');
  await expect(app.rows).toHaveCount(2);
  await page.getByRole('button', { name: 'Affichage', exact: true }).click();
  const display = page.getByRole('dialog', { name: 'Options d’affichage' });
  await display.getByRole('combobox', { name: 'Grouper les tickets' }).selectOption('none');
  await display.getByRole('combobox', { name: 'Trier par' }).selectOption('title');
  await display.getByRole('combobox', { name: 'Ordre', exact: true }).selectOption('asc');
  await display.getByRole('button', { name: 'Terminer' }).click();
  await expect(app.rows.first()).toContainText('Alpha urgent');
  await page.getByRole('button', { name: 'Enregistrer cette vue' }).click();
  const form = page.getByRole('dialog', { name: 'Enregistrer une vue' });
  await form.getByRole('textbox', { name: 'Nom de la vue' }).fill('À traiter');
  await form.getByRole('button', { name: 'Enregistrer la vue' }).click();
  await expect(form).toBeHidden();
  await page.getByRole('button', { name: 'Réinitialiser les filtres', exact: true }).click();
  await expect(app.rows).toHaveCount(3);
  await page.locator('.saved-views').getByRole('button', { name: 'À traiter', exact: true }).click();
  await expect(app.rows).toHaveCount(2);
  await page.getByRole('button', { name: 'Mettre à jour la vue' }).click();
  const edit = page.getByRole('dialog', { name: 'Modifier la vue' });
  await edit.getByRole('textbox', { name: 'Nom de la vue' }).fill('Priorités locales');
  await edit.getByRole('button', { name: 'Enregistrer la vue' }).click();
  await expect(edit).toBeHidden();
  await expect(page.locator('.settings-save-state')).toHaveText('Réglages enregistrés');
  await server.restart(); await page.reload();
  await page.locator('.saved-views').getByRole('button', { name: 'Priorités locales', exact: true }).click();
  await expect(app.rows).toHaveCount(2);
  await expect(app.statusFilter).toHaveValue('todo');
  await expect(app.priorityFilter).toHaveValue('high');
  await expect(app.rows.first()).toContainText('Alpha urgent');
  await page.getByRole('button', { name: 'Supprimer la vue Priorités locales' }).click();
  await page.getByRole('dialog', { name: 'Supprimer la vue' }).getByRole('button', { name: 'Supprimer la vue', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await server.restart(); await page.reload();
  await expect(page.locator('.saved-views').getByRole('button', { name: 'Priorités locales', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Réinitialiser les filtres', exact: true }).click();
  await expect(app.rows).toHaveCount(3);
});

test('palette au clavier et protection des préférences à la navigation', async ({ app, page }) => {
  await app.createProject('Navigation', 'NAV');
  await app.createTicket({ title: 'Retrouver une décision' });
  await page.keyboard.press('Control+k');
  const palette = page.getByRole('dialog', { name: 'Commandes et recherche' });
  const query = palette.getByRole('combobox', { name: 'Rechercher une commande ou un ticket' });
  await query.fill('Retrouver une décision');
  await expect(palette.getByRole('option')).toHaveCount(1);
  await query.press('Enter');
  await expect(app.detail.getByRole('textbox', { name: 'Titre', exact: true })).toHaveValue('Retrouver une décision');
  await app.closeDetail();
  await page.keyboard.press('Control+k');
  await query.fill('paramètres');
  await expect(palette.getByRole('option', { name: 'Ouvrir les paramètres' })).toBeVisible();
  await query.press('Enter');
  await expect(page.getByRole('heading', { name: 'Paramètres', exact: true })).toBeVisible();
  await page.getByRole('combobox', { name: 'Taille du texte', exact: true }).selectOption('large');
  page.once('dialog', dialog => dialog.dismiss());
  await page.getByRole('navigation', { name: 'Navigation principale' }).getByRole('button', { name: /^Tous les tickets/ }).click();
  await expect(page.getByRole('heading', { name: 'Paramètres', exact: true })).toBeVisible();
  await expect(page.getByRole('combobox', { name: 'Taille du texte', exact: true })).toHaveValue('large');
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('navigation', { name: 'Navigation principale' }).getByRole('button', { name: /^Tous les tickets/ }).click();
  await expect(app.rows).toHaveCount(1);
  await page.getByRole('button', { name: 'Paramètres', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Taille du texte', exact: true })).toHaveValue('default');
});

test('erreur de sauvegarde des réglages visible puis récupération persistante', async ({ app, page }) => {
  await app.createProject('Résilience des réglages', 'REG');
  await app.createTicket({ title: 'Contrôler une préférence' });
  await expect(page.locator('.settings-save-state')).toHaveText('Réglages enregistrés');
  await page.route('**/api/settings', async route => {
    if (route.request().method() === 'PATCH') await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Indisponibilité simulée' }) });
    else await route.continue();
  });
  await app.board();
  await expect(page.getByRole('alert')).toContainText('Réglages non enregistrés');
  await expect(page.getByRole('button', { name: 'Tableau', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.unroute('**/api/settings');
  await page.getByRole('button', { name: 'Réessayer l’enregistrement des réglages' }).click();
  await expect(page.locator('.settings-save-state')).toHaveText('Réglages enregistrés');
  await page.reload();
  await expect(page.getByRole('button', { name: 'Tableau', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(app.card('Contrôler une préférence')).toBeVisible();
});
