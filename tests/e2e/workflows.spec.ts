test('modifier et commenter ; les données et suppressions survivent au redémarrage réel', async ({ app, page, server }) => {
  await app.createProject('Observatoire', 'OBS');
  await app.createTicket({ title: 'Ticket initial', project: 'Observatoire' });
  await app.openTicket('Ticket initial');
  const saved = page.waitForResponse(response => /\/api\/issues\/\d+$/.test(response.url()) && response.request().method() === 'PATCH');
  await app.saveTicket({ title: 'Ticket corrigé', description: 'Texte persistant après arrêt du processus.', priority: 'urgent' });
  expect((await saved).ok()).toBeTruthy();
  await app.comment('Validation locale effectuée, sans service externe.');
  await expect(app.detail.getByText('Validation locale effectuée, sans service externe.', { exact: true })).toBeVisible();
  await app.closeDetail();
  await expect(app.row('Ticket corrigé')).toBeVisible();
  await expect(app.row('Ticket corrigé')).toBeFocused();

  await server.restart();
  await page.reload();
  await app.openTicket('Ticket corrigé');
  await expect(app.detail.getByRole('textbox', { name: 'Description', exact: true })).toHaveValue('Texte persistant après arrêt du processus.');
  await expect(app.detail.getByRole('combobox', { name: 'Priorité', exact: true })).toHaveValue('urgent');
  await expect(app.detail.getByText('Validation locale effectuée, sans service externe.', { exact: true })).toBeVisible();

  page.once('dialog', dialog => dialog.accept());
  await app.detail.getByRole('button', { name: 'Supprimer le ticket', exact: true }).click();
  await expect(app.detail).toBeHidden();
  await expect(app.rows).toHaveCount(0);
  await page.reload();
  await expect(app.rows).toHaveCount(0);
  await server.restart();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Tous les tickets', exact: true })).toBeVisible();
  await expect(app.rows).toHaveCount(0);
  const response = await page.request.get(`${server.url}/api/issues`);
  expect(response.ok()).toBeTruthy();
  expect(await response.json()).toEqual([]);
});

test('glisser un ticket entre statuts puis retrouver le déplacement après actualisation', async ({ app, page }) => {
  await app.createProject('Orbites', 'ORB');
  await app.createTicket({ title: 'Calibrer le télescope', status: 'todo' });
  await app.board();
  await expect(app.column('todo').getByText('Calibrer le télescope', { exact: true })).toBeVisible();
  const moved = page.waitForResponse(response => /\/api\/issues\/\d+$/.test(response.url()) && response.request().method() === 'PATCH');
  await app.card('Calibrer le télescope').dragTo(app.column('done'));
  expect((await moved).ok()).toBeTruthy();
  await expect(app.column('done').getByText('Calibrer le télescope', { exact: true })).toBeVisible();
  await expect(app.column('todo').getByText('Calibrer le télescope', { exact: true })).toHaveCount(0);
  await page.reload();
  await app.board();
  await expect(app.column('done').getByText('Calibrer le télescope', { exact: true })).toBeVisible();
  await app.card('Calibrer le télescope').getByRole('combobox', { name: 'Statut de ORB-1', exact: true }).focus();
  const keyboardMoved = page.waitForResponse(response => /\/api\/issues\/\d+$/.test(response.url()) && response.request().method() === 'PATCH');
  await page.keyboard.press('ArrowUp');
  expect((await keyboardMoved).ok()).toBeTruthy();
  await expect(app.column('in_review').getByText('Calibrer le télescope', { exact: true })).toBeVisible();
  await app.list();
  await app.openTicket('Calibrer le télescope');
  await expect(app.detail.getByRole('combobox', { name: 'Statut', exact: true })).toHaveValue('in_review');
});

test('recherche et filtres projet, statut, priorité se cumulent', async ({ app, page }) => {
  await app.createProject('Observatoire', 'OBS');
  await app.createProject('Navigation', 'NAV');
  await app.createTicket({ title: 'Cobalt principal', description: 'Objectif zénith', project: 'Observatoire', status: 'todo', priority: 'high' });
  await app.createTicket({ title: 'Cobalt terminé', project: 'Observatoire', status: 'done', priority: 'high' });
  await app.createTicket({ title: 'Cobalt faible', project: 'Observatoire', status: 'todo', priority: 'low' });
  await app.createTicket({ title: 'Cobalt navigation', project: 'Navigation', status: 'todo', priority: 'high' });
  await app.createTicket({ title: 'Ambre principal', project: 'Observatoire', status: 'todo', priority: 'high' });
  await expect(app.rows).toHaveCount(5);
  await app.search.fill('COBALT');
  await expect(app.rows).toHaveCount(4);
  await app.projectFilter.selectOption({ label: 'Observatoire' });
  await expect(app.rows).toHaveCount(3);
  await app.statusFilter.selectOption('todo');
  await expect(app.rows).toHaveCount(2);
  await app.priorityFilter.selectOption('high');
  await expect(app.rows).toHaveCount(1);
  await expect(app.row('Cobalt principal')).toBeVisible();
  await app.search.fill('aucun résultat inventé');
  await expect(app.rows).toHaveCount(0);
  await page.getByRole('button', { name: 'Réinitialiser les filtres', exact: true }).click();
  await expect(app.rows).toHaveCount(5);
  await app.search.fill('OBS-1');
  await expect(app.rows).toHaveCount(1);
  await expect(app.row('Cobalt principal')).toBeVisible();
  await app.search.fill('objectif zénith');
  await expect(app.rows).toHaveCount(1);
  await expect(app.row('Cobalt principal')).toBeVisible();
});

test('création clavier, recherche rapide, saisie protégée et abandon confirmé', async ({ app, page }) => {
  await app.createProject('Raccourcis', 'KEY');
  const createButton = page.getByRole('button', { name: 'Nouveau ticket', exact: true });
  await createButton.click();
  await expect(app.newTicketDialog.getByRole('textbox', { name: 'Titre', exact: true })).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(app.newTicketDialog).toBeHidden();
  await expect(createButton).toBeFocused();
  await page.getByRole('heading', { name: 'Tous les tickets', exact: true }).click();
  await page.keyboard.press('c');
  await expect(app.newTicketDialog).toBeVisible();
  await expect(app.newTicketDialog.getByRole('textbox', { name: 'Titre', exact: true })).toBeFocused();
  await page.keyboard.type('c');
  await expect(app.newTicketDialog.getByRole('textbox', { name: 'Titre', exact: true })).toHaveValue('c');
  await expect(page.getByRole('dialog')).toHaveCount(1);
  await app.fillTicket(app.newTicketDialog, { title: 'Création au clavier' });
  await page.keyboard.press('Control+Enter');
  await expect(app.newTicketDialog).toBeHidden();
  await expect(app.row('Création au clavier')).toBeVisible();
  await page.keyboard.press('/');
  await expect(app.search).toBeFocused();
  await page.keyboard.type('c');
  await expect(app.search).toHaveValue('c');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await app.search.fill('');
  await page.getByRole('heading', { name: 'Tous les tickets', exact: true }).click();
  await page.keyboard.press('c');
  await app.newTicketDialog.getByRole('textbox', { name: 'Titre', exact: true }).fill('Ne pas sauvegarder');
  page.once('dialog', dialog => dialog.dismiss());
  await page.keyboard.press('Escape');
  await expect(app.newTicketDialog).toBeVisible();
  page.once('dialog', dialog => dialog.accept());
  await page.keyboard.press('Escape');
  await expect(app.newTicketDialog).toBeHidden();
  await expect(app.rows).toHaveCount(1);
  await expect(app.row('Ne pas sauvegarder')).toHaveCount(0);
});

test('une erreur serveur conserve la saisie et permet de sauvegarder après reconnexion', async ({ app, page, server }) => {
  await app.createProject('Résilience', 'RES');
  await page.getByRole('button', { name: 'Nouveau ticket', exact: true }).click();
  await app.fillTicket(app.newTicketDialog, { title: 'Saisie conservée', description: 'Ce texte doit rester disponible.', priority: 'high' });
  await server.stop();
  await app.newTicketDialog.getByRole('button', { name: 'Créer le ticket', exact: true }).click();
  await expect(app.newTicketDialog.getByRole('alert')).toBeVisible();
  await expect(app.newTicketDialog.getByRole('textbox', { name: 'Titre', exact: true })).toHaveValue('Saisie conservée');
  await expect(app.newTicketDialog.getByRole('textbox', { name: 'Description', exact: true })).toHaveValue('Ce texte doit rester disponible.');
  await expect(app.newTicketDialog.getByRole('combobox', { name: 'Priorité', exact: true })).toHaveValue('high');
  await server.start();
  await app.newTicketDialog.getByRole('button', { name: 'Créer le ticket', exact: true }).click();
  await expect(app.newTicketDialog).toBeHidden();
  await expect(app.row('Saisie conservée')).toBeVisible();
  await page.reload();
  await expect(app.row('Saisie conservée')).toBeVisible();
});

test('gestion des projets et étiquettes : renommer, protéger un projet occupé et supprimer un projet vide', async ({ app, page, server }) => {
  await app.createProject('Projet initial', 'PRO');
  await app.createProject('Projet vide', 'VID');
  await page.getByRole('button', { name: 'Nouveau ticket', exact: true }).click();
  await app.fillTicket(app.newTicketDialog, { title: 'Ticket étiqueté', project: 'Projet initial' });
  await app.newTicketDialog.getByRole('button', { name: 'Nouvelle étiquette', exact: true }).click();
  await app.newTicketDialog.getByRole('textbox', { name: 'Nom de l’étiquette', exact: true }).fill('Documentation');
  await app.newTicketDialog.getByRole('button', { name: 'Créer l’étiquette', exact: true }).click();
  await expect(app.newTicketDialog.getByRole('checkbox', { name: 'Documentation', exact: true })).toBeChecked();
  await app.newTicketDialog.getByRole('button', { name: 'Créer le ticket', exact: true }).click();
  await expect(app.row('Ticket étiqueté').getByText('Documentation', { exact: true })).toBeVisible();
  await page.getByRole('navigation', { name: 'Navigation principale' }).getByRole('button', { name: /^Projets/ }).click();
  await page.getByRole('button', { name: 'Modifier Projet initial', exact: true }).click();
  const project = page.getByRole('dialog', { name: 'Modifier le projet', exact: true });
  await expect(project.getByRole('textbox', { name: 'Préfixe', exact: true })).toBeDisabled();
  await project.getByRole('textbox', { name: 'Nom du projet', exact: true }).fill('Projet renommé');
  await project.getByRole('button', { name: 'Enregistrer le projet', exact: true }).click();
  await expect(project).toBeHidden();
  await page.getByRole('button', { name: 'Modifier Projet renommé', exact: true }).click();
  page.once('dialog', dialog => dialog.accept());
  await project.getByRole('button', { name: 'Supprimer le projet', exact: true }).click();
  await expect(project.getByRole('alert')).toBeVisible();
  await expect(project).toBeVisible();
  await project.getByRole('button', { name: 'Fermer', exact: true }).click();
  await page.getByRole('button', { name: 'Modifier Projet vide', exact: true }).click();
  page.once('dialog', dialog => dialog.accept());
  await project.getByRole('button', { name: 'Supprimer le projet', exact: true }).click();
  await expect(project).toBeHidden();
  await expect(page.getByTestId(/^project-card-/)).toHaveCount(1);

  await server.restart();
  await page.reload();
  await page.getByRole('navigation', { name: 'Navigation principale' }).getByRole('button', { name: /^Projets/ }).click();
  await expect(page.getByRole('button', { name: 'Modifier Projet renommé', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Modifier Projet vide', exact: true })).toHaveCount(0);
  await page.getByRole('navigation', { name: 'Navigation principale' }).getByRole('button', { name: /^Tous les tickets/ }).click();
  await app.openTicket('Ticket étiqueté');
  await expect(app.detail.getByRole('checkbox', { name: 'Documentation', exact: true })).toBeChecked();
  await expect(app.detail.getByRole('combobox', { name: 'Projet', exact: true }).getByRole('option', { name: 'Projet renommé' })).toHaveJSProperty('selected', true);
});
